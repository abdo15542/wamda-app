package net.wamdalibya.app

import android.app.Activity
import android.content.Context
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.GetCredentialResponse
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.GoogleAuthProvider
import kotlinx.coroutines.tasks.await

/**
 * Google Sign-In through Credential Manager (one-tap) — v3.1.
 *
 * First time: the user taps "Sign in with Google" once and picks their
 * Google account (Android requires that one tap — no app can skip it).
 * Afterwards sign-in is automatic: Firebase Auth persists the user, and
 * [trySilentGoogleLink] re-links on launch when the device linked
 * Google before, with no UI at all.
 *
 * The Google credential is LINKED to the current anonymous account
 * whenever one exists, so the Firebase uid is PRESERVED — the user's
 * existing likes and comments survive the sign-in. Sign-out returns the
 * device to a fresh anonymous user (likes keep working).
 *
 * The server client id comes ONLY from R.string.default_web_client_id,
 * generated by the google-services plugin from google-services.json —
 * never hardcoded. The json MUST contain the Web OAuth client (type 3);
 * without it the string resource is not generated and the build fails.
 *
 * Every function here is failure-safe: user-cancel, no Google account
 * on the device, no network, or a missing client id all return null /
 * do nothing — never throw, never crash, never show a stack trace.
 */
data class GoogleSignInResult(val uid: String, val displayName: String?)

private const val AUTH_PREFS = "wamda_auth"
private const val KEY_GOOGLE_LINKED = "google_linked"

/** True when this device linked a Google account before. */
fun isGoogleLinked(context: Context): Boolean =
    context.getSharedPreferences(AUTH_PREFS, Context.MODE_PRIVATE)
        .getBoolean(KEY_GOOGLE_LINKED, false)

private fun setGoogleLinked(context: Context, linked: Boolean) {
    context.getSharedPreferences(AUTH_PREFS, Context.MODE_PRIVATE)
        .edit().putBoolean(KEY_GOOGLE_LINKED, linked).apply()
}

/**
 * Interactive one-tap sign-in. Shows the Google account picker once;
 * returns the uid + Google display name, or null on cancel / failure.
 */
suspend fun signInWithGoogle(activity: Activity): GoogleSignInResult? {
    return try {
        val option = GetGoogleIdOption.Builder()
            .setFilterByAuthorizedAccounts(false)
            .setServerClientId(activity.getString(R.string.default_web_client_id))
            .build()
        val request = GetCredentialRequest.Builder()
            .addCredentialOption(option)
            .build()
        val response = CredentialManager.create(activity)
            .getCredential(context = activity, request = request)
        linkGoogleCredential(activity, response)
    } catch (e: Exception) {
        // Cancelled, no Google account, no network, or the web client id
        // is missing — stay anonymous, no error shown.
        null
    }
}

/**
 * Silent re-link on launch: only when the device linked Google before.
 * Returns the uid + display name, or null on any failure — the caller
 * must stay anonymous and never prompt.
 *
 * NOTE: googleid 1.1.1 has no preferImmediatelyAvailableCredentials()
 * (that arrived in a later googleid release); the 1.1.1-era silent path
 * is filterByAuthorizedAccounts(true) + setAutoSelectEnabled(true),
 * which returns the one previously-authorized account without UI.
 */
suspend fun trySilentGoogleLink(activity: Activity): GoogleSignInResult? {
    if (!isGoogleLinked(activity)) return null
    return try {
        val option = GetGoogleIdOption.Builder()
            .setFilterByAuthorizedAccounts(true)
            .setServerClientId(activity.getString(R.string.default_web_client_id))
            .setAutoSelectEnabled(true)
            .build()
        val request = GetCredentialRequest.Builder()
            .addCredentialOption(option)
            .build()
        val response = CredentialManager.create(activity)
            .getCredential(context = activity, request = request)
        linkGoogleCredential(activity, response)
    } catch (e: Exception) {
        null
    }
}

/** Turns a Google ID-token credential into a Firebase user (link or sign-in). */
private suspend fun linkGoogleCredential(
    context: Context,
    response: GetCredentialResponse
): GoogleSignInResult? {
    val credential = response.credential
    if (credential !is CustomCredential ||
        credential.type != GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
    ) {
        return null
    }
    val googleId = GoogleIdTokenCredential.createFrom(credential.data)
    val firebaseCredential = GoogleAuthProvider.getCredential(googleId.idToken, null)
    val auth = FirebaseAuth.getInstance()
    val current = auth.currentUser
    val result = if (current != null && current.isAnonymous) {
        // LINK: the anonymous uid is preserved — likes/comments survive.
        current.linkWithCredential(firebaseCredential).await()
    } else {
        auth.signInWithCredential(firebaseCredential).await()
    }
    val user = result.user ?: return null
    setGoogleLinked(context, true)
    return GoogleSignInResult(user.uid, user.displayName)
}

/**
 * Signs out of Google and forgets the link. The caller must sign the
 * device in anonymously again afterwards (SocialRepository.ensureSignedIn)
 * so likes and comments keep working.
 */
fun signOutOfGoogle(context: Context) {
    try {
        FirebaseAuth.getInstance().signOut()
    } catch (e: Exception) {
        // Sign-out must never crash the app.
    }
    setGoogleLinked(context, false)
}
