/**
 * Google Sign-In through Credential Manager (one-tap) — v3.1.
 *
 * First time: the user taps "Sign in with Google" once and picks their
 * Google account (Android requires that one tap — no app can skip it).
 * Afterwards sign-in is automatic: Firebase Auth persists the user, and
 * [trySilentGoogleLink] re-links on launch when the device linked
 * Google before, with no UI at all.
 *
 * The Google credential is LINKED to the current anonymous account
 * whenever one exists, so the Firebase uid is PRESERVED — the user's
 * existing likes and comments survive the sign-in. Sign-out returns the
 * device to a fresh anonymous user (likes keep working).
 *
 * The server client id comes ONLY from R.string.default_web_client_id,
 * generated by the google-services plugin from google-services.json —
 * never hardcoded. The json MUST contain the Web OAuth client (type 3);
 * without it the string resource is not generated and the build fails.
 *
 * Every function here is failure-safe: user-cancel, no Google account
 * on the device, no network, or a missing client id all return null /
 * do nothing — never throw, never crash, never show a stack trace.
 *
 * v3.2: the interactive sign-in NEVER swallows its failure into a
 * generic message any more. signInWithGoogle returns a
 * GoogleSignInOutcome: Success, Cancelled (the user dismissed the
 * Google picker themselves — not an error, nothing shown), or Failed
 * carrying the REAL exception (class name + Firebase errorCode when
 * present + message), which the account dialog shows verbatim and
 * which is also logged in full to Logcat.
 *
 * v3.4: when Credential Manager fails to provide ANY Google credential
 * (GetCredentialException — in practice NoCredentialException, seen on
 * Abdoo's phone 2026-11-25 even though Google accounts exist on the
 * device and sign-in works in other apps), signInWithGoogle falls back
 * to the CLASSIC Google Sign-In flow (GoogleSignInClient, the same
 * flow other apps use). The classic flow shows the account picker
 * directly and even lets the user add a Google account on the spot.
 * It needs the same Web client id + SHA-1 the Credential Manager flow
 * already uses — no new console setup. MainActivity forwards its
 * onActivityResult to LegacyGoogleSignIn (request code 9001).
 */
data class GoogleSignInResult(val uid: String, val displayName: String?)

/** Outcome of an interactive Google sign-in attempt (v3.2). */
sealed class GoogleSignInOutcome {
    data class Success(val result: GoogleSignInResult) : GoogleSignInOutcome()
    /** The user dismissed the Google picker themselves — not an error. */
    object Cancelled : GoogleSignInOutcome()
    /**
     * A real failure. code = the exception's class (Firebase errors
     * also carry their errorCode, e.g. "FirebaseAuthException
     * (ERROR_INVALID_CREDENTIAL)"); detail = the exception message.
     */
    data class Failed(val code: String, val detail: String?) : GoogleSignInOutcome()
}

private const val TAG = "GoogleSignIn"
private const val AUTH_PREFS = "wamda_auth"
private const val KEY_GOOGLE_LINKED = "google_linked"

/** True when this device linked a Google account before. */
fun isGoogleLinked(context: Context): Boolean =
    context.getSharedPreferences(AUTH_PREFS, Context.MODE_PRIVATE)
        .getBoolean(KEY_GOOGLE_LINKED, false)

private fun setGoogleLinked(context: Context, linked: Boolean) {
    context.getSharedPreferences(AUTH_PREFS, Context.MODE_PRIVATE)
        .edit().putBoolean(KEY_GOOGLE_LINKED, linked).apply()
}

/**
 * Interactive one-tap sign-in. Shows the Google account picker once.
 * Returns Success (uid + Google display name), Cancelled (the user
 * dismissed the picker — not an error), or Failed with the REAL
 * exception (code + message), logged in full to Logcat. Never throws.
 */
suspend fun signInWithGoogle(activity: Activity): GoogleSignInOutcome {
    return try {
        val option = GetGoogleIdOption.Builder()
            .setFilterByAuthorizedAccounts(false)
            .setServerClientId(activity.getString(R.string.default_web_client_id))
            .build()
        val request = GetCredentialRequest.Builder()
            .addCredentialOption(option)
            .build()
        val response = CredentialManager.create(activity)
            .getCredential(context = activity, request = request)
        val linked = linkGoogleCredential(activity, response)
        if (linked != null) {
            GoogleSignInOutcome.Success(linked)
        } else {
            // A credential came back but it was not a Google ID token —
            // a real failure, not a cancel; say so plainly.
            Log.e(TAG, "Google sign-in failed: credential was not a Google ID token")
            GoogleSignInOutcome.Failed("NoGoogleIdToken", null)
        }
    } catch (e: GetCredentialCancellationException) {
        // The user backed out of the Google picker (e.g. dismissed the
        // "unverified app" warning) — their choice, not an error:
        // nothing is shown, the dialog just stays open.
        GoogleSignInOutcome.Cancelled
    } catch (e: GetCredentialException) {
        // v3.4 FALLBACK: Credential Manager could not provide any Google
        // credential on this device (NoCredentialException even though
        // accounts exist — seen on Abdoo's phone 2026-11-25, where
        // sign-in works fine in other apps). The classic Google Sign-In
        // flow is what those apps use, so try it before giving up.
        Log.w(TAG, "Credential Manager failed (${e::class.java.simpleName}); trying legacy Google sign-in", e)
        signInWithGoogleLegacy(activity)
    } catch (e: Exception) {
        // The real error, in full, to Logcat — and carried back so the
        // dialog can show it instead of a generic "check connection".
        Log.e(TAG, "Google sign-in failed", e)
        GoogleSignInOutcome.Failed(failureCode(e), e.message)
    }
}

/**
 * Short code for a sign-in failure: the exception class; Firebase
 * auth errors also carry their errorCode (e.g. ERROR_INVALID_CREDENTIAL,
 * ERROR_ACCOUNT_EXISTS_WITH_DIFFERENT_CREDENTIAL).
 */
private fun failureCode(e: Exception): String {
    val base = e::class.java.simpleName
    return if (e is FirebaseAuthException) "$base (${e.errorCode})" else base
}

/**
 * Silent re-link on launch: only when the device linked Google before.
 * Returns the uid + display name, or null on any failure — the caller
 * must stay anonymous and never prompt.
 *
 * NOTE: googleid 1.1.1 has no preferImmediatelyAvailableCredentials()
 * (that arrived in a later googleid release); the 1.1.1-era silent path
 * is filterByAuthorizedAccounts(true) + setAutoSelectEnabled(true),
 * which returns the one previously-authorized account without UI.
 */
suspend fun trySilentGoogleLink(activity: Activity): GoogleSignInResult? {
    if (!isGoogleLinked(activity)) return null
    return try {
        val option = GetGoogleIdOption.Builder()
            .setFilterByAuthorizedAccounts(true)
            .setServerClientId(activity.getString(R.string.default_web_client_id))
            .setAutoSelectEnabled(true)
            .build()
        val request = GetCredentialRequest.Builder()
            .addCredentialOption(option)
            .build()
        val response = CredentialManager.create(activity)
            .getCredential(context = activity, request = request)
        linkGoogleCredential(activity, response)
    } catch (e: Exception) {
        // Silent path: still log it — a failing silent re-link is the
        // first thing to check when sign-in "stops working" — but never
        // show anything: the caller stays anonymous and never prompts.
        Log.w(TAG, "Silent Google re-link failed", e)
        null
    }
}

/** Turns a Google ID-token credential into a Firebase user (link or sign-in). */
private suspend fun linkGoogleCredential(
    context: Context,
    response: GetCredentialResponse
): GoogleSignInResult? {
    val credential = response.credential
    if (credential !is CustomCredential ||
        credential.type != GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
    ) {
        return null
    }
    val googleId = GoogleIdTokenCredential.createFrom(credential.data)
    return linkGoogleIdToken(context, googleId.idToken)
}

/**
 * Turns a Google ID token into a Firebase user (link or sign-in).
 * Shared by the Credential Manager path and the v3.4 legacy fallback.
 * Throws on a Firebase failure (e.g. ERROR_INVALID_CREDENTIAL) — the
 * caller turns it into a Failed outcome with the real error code.
 */
private suspend fun linkGoogleIdToken(
    context: Context,
    idToken: String
): GoogleSignInResult? {
    val firebaseCredential = GoogleAuthProvider.getCredential(idToken, null)
    val auth = FirebaseAuth.getInstance()
    val current = auth.currentUser
    val result = if (current != null && current.isAnonymous) {
        // LINK: the anonymous uid is preserved — likes/comments survive.
        current.linkWithCredential(firebaseCredential).await()
    } else {
        auth.signInWithCredential(firebaseCredential).await()
    }
    val user = result.user ?: return null
    setGoogleLinked(context, true)
    return GoogleSignInResult(user.uid, user.displayName)
}

/**
 * Classic Google Sign-In fallback (v3.4) — the flow other apps use.
 * Shows the Google account picker directly (the user can even add a
 * Google account on the spot). The result arrives through
 * MainActivity.onActivityResult -> LegacyGoogleSignIn.onActivityResult.
 * The 5-minute timeout only guards a leaked wait (e.g. the activity
 * was destroyed mid-flow); a normal cancel arrives as Cancelled.
 */
suspend fun signInWithGoogleLegacy(activity: Activity): GoogleSignInOutcome {
    return try {
        val options = GoogleSignInOptions.Builder(GoogleSignInOptions.DEFAULT_SIGN_IN)
            .requestIdToken(activity.getString(R.string.default_web_client_id))
            .requestEmail()
            .build()
        val client = GoogleSignIn.getClient(activity, options)
        val deferred = CompletableDeferred<LegacyResult>()
        LegacyGoogleSignIn.setPending(deferred)
        // startActivityForResult must run on the Main thread (this
        // function is normally called from Dispatchers.IO).
        withContext(Dispatchers.Main) {
            activity.startActivityForResult(
                client.signInIntent, LegacyGoogleSignIn.REQUEST_CODE
            )
        }
        val result = withTimeoutOrNull(300_000L) { deferred.await() }
            ?: LegacyResult.Failed("LegacyTimeout", null)
        LegacyGoogleSignIn.clearPending()
        when (result) {
            is LegacyResult.Token -> {
                val linked = try {
                    linkGoogleIdToken(activity, result.idToken)
                } catch (e: Exception) {
                    Log.e(TAG, "Legacy Google sign-in: Firebase link failed", e)
                    return GoogleSignInOutcome.Failed(failureCode(e), e.message)
                }
                if (linked != null) GoogleSignInOutcome.Success(linked)
                else GoogleSignInOutcome.Failed("LinkFailed", null)
            }
            LegacyResult.Cancelled -> GoogleSignInOutcome.Cancelled
            is LegacyResult.Failed -> GoogleSignInOutcome.Failed(result.code, result.detail)
        }
    } catch (e: Exception) {
        LegacyGoogleSignIn.clearPending()
        Log.e(TAG, "Legacy Google sign-in failed", e)
        GoogleSignInOutcome.Failed(failureCode(e), e.message)
    }
}

private sealed interface LegacyResult {
    data class Token(val idToken: String) : LegacyResult
    object Cancelled : LegacyResult
    data class Failed(val code: String, val detail: String?) : LegacyResult
}

/**
 * Holds the one in-flight legacy sign-in. MainActivity forwards its
 * onActivityResult here; the awaiting coroutine in
 * signInWithGoogleLegacy then links the token to Firebase.
 */
object LegacyGoogleSignIn {
    const val REQUEST_CODE = 9001
    private var pending: CompletableDeferred<LegacyResult>? = null

    fun setPending(deferred: CompletableDeferred<LegacyResult>) {
        pending = deferred
    }

    fun clearPending() {
        pending = null
    }

    fun onActivityResult(resultCode: Int, data: Intent?) {
        val deferred = pending ?: return
        pending = null
        if (resultCode != Activity.RESULT_OK) {
            // The user backed out of the account picker — their choice,
            // not an error.
            deferred.complete(LegacyResult.Cancelled)
            return
        }
        val result: LegacyResult = try {
            val task = GoogleSignIn.getSignedInAccountFromIntent(data)
            val account = task.getResult(ApiException::class.java)
            val idToken = account?.idToken
            if (idToken.isNullOrBlank()) LegacyResult.Failed("NoGoogleIdToken", null)
            else LegacyResult.Token(idToken)
        } catch (e: ApiException) {
            // 12501 = the user cancelled the picker; anything else is a
            // real failure (e.g. 10 = DEVELOPER_ERROR, a console misconfig).
            if (e.statusCode == 12501) LegacyResult.Cancelled
            else LegacyResult.Failed("ApiException (${e.statusCode})", e.message)
        } catch (e: Exception) {
            LegacyResult.Failed(e::class.java.simpleName, e.message)
        }
        deferred.complete(result)
    }
}

/**
 * Signs out of Google and forgets the link. The caller must sign the
 * device in anonymously again afterwards (SocialRepository.ensureSignedIn)
 * so likes and comments keep working.
 */
fun signOutOfGoogle(context: Context) {
    try {
        FirebaseAuth.getInstance().signOut()
    } catch (e: Exception) {
        // Sign-out must never crash the app.
    }
    setGoogleLinked(context, false)
}
